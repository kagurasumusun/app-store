#!/usr/bin/env python3
"""Generate Core SAP constant tables from the vendored data in ThirdParty/sap-tables.

The data files are interoperability constants for Apple's FairPlay SAP
protocol (see ThirdParty/sap-tables/README.md for provenance and licensing).
This script only re-encodes that fixed data as C++ arrays; all algorithm code
is implemented independently in Core/src/sap_software.cpp.
"""
import hashlib
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DATA = ROOT / "ThirdParty" / "sap-tables"
HEADER = ROOT / "Core" / "include" / "ipashelf" / "sap_tables.hpp"
SOURCE = ROOT / "Core" / "src" / "sap_tables.cpp"

EXPECTED = {
    "byte-tables.bin": (51200, "a40bb580f1012b06b8b257926b76bb02ec98033f6399da2143c963d36dbe0aae"),
    "word-tables.bin": (73728, "6eeffb5e403a54a3b51baa67cf0b7abc23271da404fef4cae9e06c9753833340"),
    "carry-masks.bin": (964, "f0396c6119faafecc811c33a61433faacbfb685d157f198da920183b240285d0"),
    "f2-tables.bin": (18432, "f811dd378e1e8e05a9d3697111c4fb1d4afe2acdf81a1fcde69fe231bc975876"),
    "rng-tables.bin": (2320, None),
}


def load(name):
    blob = (DATA / name).read_bytes()
    size, digest = EXPECTED[name]
    if len(blob) != size:
        sys.exit(f"{name}: expected {size} bytes, got {len(blob)}")
    if digest and hashlib.sha256(blob).hexdigest() != digest:
        sys.exit(f"{name}: SHA-256 mismatch")
    return blob


def emit_bytes(symbol, blob):
    lines = [f"const std::uint8_t {symbol}[{len(blob)}] = {{"]
    for offset in range(0, len(blob), 16):
        chunk = ",".join(f"0x{b:02x}" for b in blob[offset:offset + 16])
        lines.append(f"    {chunk},")
    lines.append("};")
    return "\n".join(lines)


def main():
    byte_tables = load("byte-tables.bin")
    word_tables = load("word-tables.bin")
    carry_masks = load("carry-masks.bin")
    f2_tables = load("f2-tables.bin")
    rng_tables = load("rng-tables.bin")
    f2 = json.loads((DATA / "f2-parameters.json").read_text())

    assert len(f2["entryPositions"]) == 16 and len(f2["finalPositions"]) == 16
    assert len(f2["expansion"]) == 10
    assert len(f2["keySelections"]) == 11 and all(len(r) == 16 for r in f2["keySelections"])
    assert len(f2["mainRouting"]) == 9 and all(len(r) == 16 for r in f2["mainRouting"])
    assert all(len(s["selection"]) <= 8 for s in f2["expansion"])
    assert all(len(s["words"]) <= 12 for row in f2["keySelections"] for s in row)
    assert all(len(s["destinations"]) == 4 for row in f2["mainRouting"] for s in row)

    header = """// SPDX-License-Identifier: MIT
//
// Generated by Scripts/generate_sap_tables.py from the fixed interoperability
// constants in ThirdParty/sap-tables (see that directory's README.md for
// provenance). Do not edit by hand.

#pragma once

#include <cstddef>
#include <cstdint>

namespace ipashelf::sap_tables {

inline constexpr std::size_t kByteTablesSize = 51200;   // 200 tables x 256 B
inline constexpr std::size_t kWordTablesSize = 73728;   // 72 tables x 256 LE words
inline constexpr std::size_t kCarryMasksSize = 964;     // 233 + 239 + 241 + 251
inline constexpr std::size_t kF2TablesSize = 18432;
inline constexpr std::size_t kRngTablesSize = 2320;

extern const std::uint8_t kByteTables[kByteTablesSize];
extern const std::uint8_t kWordTables[kWordTablesSize];
extern const std::uint8_t kCarryMasks[kCarryMasksSize];
extern const std::uint8_t kF2Tables[kF2TablesSize];

// Layout: IV whitening [0,256), F1 whitening [256,512), exchange whitening
// [512,768), initialize whitening [768,1024), F1 template [1024,1280),
// F1 G tables [1280,2304), F1 round constants [2304,2320).
extern const std::uint8_t kRngTables[kRngTablesSize];

struct F2ExpansionStep {
  std::uint8_t selection[8];
  std::uint8_t selection_count;
  std::uint32_t whitening;
};

struct F2KeySelection {
  std::uint8_t shift;
  std::uint8_t words[12];
  std::uint8_t word_count;
  std::uint8_t whitening;
  std::int16_t linear;
};

struct F2Routing {
  std::uint8_t table;
  std::uint8_t destinations[4];
};

extern const std::uint8_t kF2EntryPositions[16];
extern const std::uint8_t kF2FinalPositions[16];
extern const F2ExpansionStep kF2Expansion[10];
extern const F2KeySelection kF2KeySelections[11][16];
extern const F2Routing kF2MainRouting[9][16];

}  // namespace ipashelf::sap_tables
"""

    out = [
        "// SPDX-License-Identifier: MIT",
        "//",
        "// Generated by Scripts/generate_sap_tables.py from the fixed",
        "// interoperability constants in ThirdParty/sap-tables (see that",
        "// directory's README.md for provenance and licensing). The tables are",
        "// data only; the algorithm that consumes them is implemented",
        "// independently in Core/src/sap_software.cpp. Do not edit by hand.",
        "",
        '#include "ipashelf/sap_tables.hpp"',
        "",
        "namespace ipashelf::sap_tables {",
        "",
        emit_bytes("kByteTables", byte_tables),
        "",
        emit_bytes("kWordTables", word_tables),
        "",
        emit_bytes("kCarryMasks", carry_masks),
        "",
        emit_bytes("kF2Tables", f2_tables),
        "",
        emit_bytes("kRngTables", rng_tables),
        "",
        "const std::uint8_t kF2EntryPositions[16] = {"
        + ",".join(str(v) for v in f2["entryPositions"]) + "};",
        "const std::uint8_t kF2FinalPositions[16] = {"
        + ",".join(str(v) for v in f2["finalPositions"]) + "};",
        "",
        "const F2ExpansionStep kF2Expansion[10] = {",
    ]
    for step in f2["expansion"]:
        sel = list(step["selection"]) + [0] * (8 - len(step["selection"]))
        out.append(
            "    {{" + ",".join(str(v) for v in sel) + "}, "
            + str(len(step["selection"])) + f", 0x{step['whitening']:08x}u" + "},"
        )
    out.append("};")
    out.append("")
    out.append("const F2KeySelection kF2KeySelections[11][16] = {")
    for row in f2["keySelections"]:
        out.append("    {")
        for sel in row:
            words = list(sel["words"]) + [0] * (12 - len(sel["words"]))
            out.append(
                "        {" + str(sel["shift"]) + ", {"
                + ",".join(str(v) for v in words) + "}, "
                + str(len(sel["words"])) + f", 0x{sel['whitening']:02x}, "
                + str(sel["linear"]) + "},"
            )
        out.append("    },")
    out.append("};")
    out.append("")
    out.append("const F2Routing kF2MainRouting[9][16] = {")
    for row in f2["mainRouting"]:
        out.append("    {")
        for route in row:
            out.append(
                "        {" + str(route["table"]) + ", {"
                + ",".join(str(v) for v in route["destinations"]) + "}},"
            )
        out.append("    },")
    out.append("};")
    out.append("")
    out.append("}  // namespace ipashelf::sap_tables")
    out.append("")

    HEADER.write_text(header)
    SOURCE.write_text("\n".join(out))
    print(f"wrote {HEADER.relative_to(ROOT)} and {SOURCE.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
